# shellcheck shell=bash
# Lab-specific setup for dapr-secrets. The dapr-sandbox module builds the VM startup script as
# `( export <inputs>; source /usr/local/lib/dapr-sandbox/sandbox-setup.sh; <this lab script> )`
# under `set -euo pipefail`, and writes the ready marker itself once the subshell succeeds. So the
# module's shared setup has already run when this file starts: Docker is up, DNS and outbound HTTPS
# work, the demo repo is cloned at the pinned ref, the Editor and Dev Dashboard run, and
# `dapr init` is done. Available here: the functions `log`, `die`, `bounded`, `wait_for_docker`
# and the variables HOME, TRACKS_SRC_DIR, LAB_SETUP_LOG. -e/-u/pipefail are inherited, `exit` only
# leaves the subshell, and nothing here may touch the marker.
#
# This file is appended after seed-vault.sh (which defines seed_vault) in the lab_startup_script.
# It only adds what is specific to this lab: secrets.json, the seeded Vault and the background
# pre-build of the demo apps. Safe to re-run: Vault is re-seeded, secrets.json is overwritten
# with identical bytes.
: "${TRACKS_SRC_DIR:?TRACKS_SRC_DIR must be set (set by the module sandbox-setup.sh)}"

# secrets.json is generated by copying the committed template, the single owner of the secret
# values (also used to seed Vault). The copy truncates, so a re-run leaves identical bytes.
if [ ! -f "$TRACKS_SRC_DIR/secrets/secrets.example.json" ]; then
    die "$TRACKS_SRC_DIR/secrets/secrets.example.json not found. Is $TRACKS_SRC_DIR a current clone of diagrid-labs/ai-agent-tracks-instruqt?"
fi
cp "$TRACKS_SRC_DIR/secrets/secrets.example.json" "$TRACKS_SRC_DIR/secrets/secrets.json"

# seed_vault comes from seed-vault.sh. On the VM it is concatenated in front of this script; in a
# standalone run (local, tests) it is sourced from next to this file.
if ! declare -F seed_vault >/dev/null; then
    # shellcheck source=/dev/null
    source "$(dirname "${BASH_SOURCE[0]}")/seed-vault.sh"
fi
log "starting and seeding Vault"
seed_vault "$TRACKS_SRC_DIR/secrets/secrets.json"
log "Vault seeded (${SECONDS}s since start)"

# Pre-build all demo apps in a fully detached background job (own stdin, stdout and stderr), so
# the sandbox reports ready without waiting for the builds: demo 1 first (labs 1, 2 and 4),
# then the two scoping apps of demo 2 (lab 3). Folder names follow each language: PascalCase
# for .NET, kebab-case for Python and Java. A learner who runs `dapr run -f .` before a build has
# finished only waits for that build. A failed build is logged and never fails the lab. Progress:
# `tail -f /var/log/lab-prebuild.log`.
SECRETS_BASE="$TRACKS_SRC_DIR/secrets"
PREBUILD_LOG="${LAB_PREBUILD_LOG:-/var/log/lab-prebuild.log}"
touch "$PREBUILD_LOG" 2>/dev/null || PREBUILD_LOG=/dev/null
nohup bash -s -- "$SECRETS_BASE" >>"$PREBUILD_LOG" 2>&1 <<'PREBUILD' &
base="$1"
build() { # build <dir> <command...>
    local dir="$1"; shift
    if [ -d "$dir" ]; then
        echo "$(date -u +%H:%M:%S) == $dir: $*"
        (cd "$dir" && "$@" </dev/null) || echo "WARN: build failed in $dir"
    fi
}
build "$base/dotnet/Demo1-ReadSecret" dotnet build
build "$base/python/demo1-read-secret" uv sync
build "$base/java/demo1-read-secret" mvn -q -DskipTests package
for app in AppA AppB; do
    build "$base/dotnet/Demo2-Scoping/$app" dotnet build
done
for app in app-a app-b; do
    build "$base/python/demo2-scoping/$app" uv sync
    build "$base/java/demo2-scoping/$app" mvn -q -DskipTests package
done
echo "$(date -u +%H:%M:%S) == prebuild done"
PREBUILD
log "demo pre-build started in the background (/var/log/lab-prebuild.log)"
log "done after ${SECONDS}s"
